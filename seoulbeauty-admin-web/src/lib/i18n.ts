const DICTIONARIES: Record<Locale, Partial<Record<MessageKey, string>>> = { ko, uz };

export type Vars = Record<string, string | number>;

/** Looks the key up (Korean when the chosen language has no text for it) and fills in {name} placeholders. */
export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const template = DICTIONARIES[locale][key] ?? ko[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export type Translate = (key: MessageKey, vars?: Vars) => string;
export const makeTranslate = (locale: Locale): Translate => (key, vars) => translate(locale, key, vars);
